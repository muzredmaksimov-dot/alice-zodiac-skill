def handler(event, context):
    """Главная функция обработки запросов к навыку"""
    
    # Получаем текст запроса от пользователя
    if 'request' in event and 'command' in event['request']:
        user_text = event['request']['command'].lower().strip()
    else:
        user_text = ""
    
    # Получаем данные из хранилища (если есть)
    session_state = event.get('session_state', {})
    
    # Шаг 1: Пользователь только запустил навык
    if user_text in ["", "запусти навык", "совместимость", "гороскоп"]:
        text = "🌟 Привет! Я помогу узнать совместимость по знакам зодиака. Назови свой знак и знак партнёра. Например: 'Лев и Рыбы' или просто первый знак."
        return {
            'response': {'text': text, 'end_session': False},
            'session_state': session_state,
            'version': '1.0'
        }
    
    # Распознаём знаки зодиака
    zodiacs = {
        "овен", "телец", "близнецы", "рак", "лев", "дева",
        "весы", "скорпион", "стрелец", "козерог", "водолей", "рыбы"
    }
    
    found_signs = [word for word in user_text.split() if word in zodiacs]
    
    # Случай 1: В одной фразе названы два знака
    if len(found_signs) >= 2:
        sign1, sign2 = found_signs[0], found_signs[1]
        answer = get_compatibility(sign1, sign2)
        answer += " Хочешь проверить другую пару? Просто назови новые знаки."
        return {
            'response': {'text': answer, 'end_session': False},
            'session_state': {},
            'version': '1.0'
        }
    
    # Случай 2: Назван один знак, и у нас уже есть сохранённый первый
    elif len(found_signs) == 1 and 'first_sign' in session_state:
        sign1 = session_state['first_sign']
        sign2 = found_signs[0]
        answer = get_compatibility(sign1, sign2)
        answer += " Хочешь проверить другую пару? Просто назови новые знаки."
        return {
            'response': {'text': answer, 'end_session': False},
            'session_state': {},
            'version': '1.0'
        }
    
    # Случай 3: Назван один знак, и это первый в диалоге
    elif len(found_signs) == 1:
        session_state['first_sign'] = found_signs[0]
        text = f"Запомнил: {found_signs[0].capitalize()}. А теперь назови знак партнёра."
        return {
            'response': {'text': text, 'end_session': False},
            'session_state': session_state,
            'version': '1.0'
        }
    
    # Случай 4: Ничего не распознали
    else:
        text = "Не понял знак. Назови один из 12 знаков зодиака: Овен, Телец, Близнецы, Рак, Лев, Дева, Весы, Скорпион, Стрелец, Козерог, Водолей или Рыбы."
        return {
            'response': {'text': text, 'end_session': False},
            'session_state': session_state,
            'version': '1.0'
        }
